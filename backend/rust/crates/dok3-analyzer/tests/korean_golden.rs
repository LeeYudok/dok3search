#[test]
fn preserves_spans_and_deduplicates_only_queries() {
    let input = "⚙ 검색결과의, 검색결과의";
    assert_eq!(
        word_spans(input).collect::<Vec<_>>(),
        [(4, 19, "검색결과의"), (21, 36, "검색결과의")]
    );
    let expanded = ["검색결과의", "검색결과", "검색", "결과"];
    assert_eq!(normalize_query_terms(input), expanded);
    assert_eq!(
        analyze_text(input, AnalyzeOptions::default()).terms,
        expanded.repeat(2)
    );
    assert_eq!(
        analyze_text(
            input,
            AnalyzeOptions {
                split_identifiers: false,
                char_ngrams: false
            }
        )
        .terms,
        ["검색결과의", "검색결과의"]
    );
}
